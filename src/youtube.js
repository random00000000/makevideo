// YouTube / TikTok publish package: a 1280x720 thumbnail and a description with chapter
// timestamps and the image credits every CC BY / BY-SA license requires.
import fs from 'node:fs';
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { makeLayout, setFont, wrap, titleFace } from './draw.js';

const stamp = (t) => {
  const s = Math.floor(t), h = Math.floor(s / 3600), m = Math.floor(s / 60) % 60;
  return (h ? `${h}:${String(m).padStart(2, '0')}` : `${m}`) + ':' + String(s % 60).padStart(2, '0');
};

/** YouTube chapters: first at 0:00, at least 3, each at least 10 s apart (YouTube's rules). */
export function chapters(timeline) {
  const named = timeline.filter((tl, i) => i === 0 || tl.scene.type === 'chapter');
  const pick = named.length >= 3 ? named : timeline.filter((tl, i) => i === 0 || tl.scene.title);
  const out = [];
  for (const tl of pick) {
    const at = out.length ? tl.offset : 0;
    if (out.length && at - out[out.length - 1].at < 10) continue;
    const label = out.length ? (tl.scene.title || tl.scene.type) : 'Intro';
    out.push({ at, label });
  }
  return out.length >= 3 ? out : [];
}

export async function writeYouTubePackage(spec, timeline, base, credits) {
  // thumbnail: the first stock/hero image, darkened on the left, huge title in the display face
  const W = 1280, H = 720;
  const c = createCanvas(W, H), ctx = c.getContext('2d');
  const L = makeLayout({ ...spec, width: W, height: H }, timeline[0].scene, { assets: {}, index: 0, count: 1, cues: [], reveals: [] });
  const hero = timeline.find((tl) => tl.scene.srcPath && /\.(png|jpe?g|webp)$/i.test(tl.scene.srcPath));
  ctx.fillStyle = L.theme.bg[0]; ctx.fillRect(0, 0, W, H);
  if (hero) {
    const img = await loadImage(fs.readFileSync(hero.scene.srcPath));
    const s = Math.max(W / img.width, H / img.height);
    ctx.drawImage(img, (W - img.width * s) / 2 + W * 0.12, (H - img.height * s) / 2, img.width * s, img.height * s);
  }
  const g = ctx.createLinearGradient(0, 0, W, 0);
  g.addColorStop(0, 'rgba(0,0,0,0.92)'); g.addColorStop(0.55, 'rgba(0,0,0,0.55)'); g.addColorStop(1, 'rgba(0,0,0,0.05)');
  ctx.fillStyle = g; ctx.fillRect(0, 0, W, H);
  // keep abbreviations with the next word ("T. rex", "Dr. Who") so a line never ends on "T."
  const words = String(spec.thumbnailText || spec.title).replace(/\*/g, '').replace(/\b(\w{1,3}\.) /g, '$1 ');
  let size = 120;
  let ls;
  for (;;) {
    setFont(ctx, L, size, 900, titleFace(L) || 'display');
    ls = wrap(ctx, words, W * 0.56);
    if (ls.length <= 3 || size < 60) break;
    size -= 6;
  }
  const lh = size * 1.06, top = (H - ls.length * lh) / 2;
  ctx.textBaseline = 'top'; ctx.textAlign = 'left';
  ctx.save(); ctx.shadowColor = 'rgba(0,0,0,0.8)'; ctx.shadowBlur = 24;
  ls.forEach((line, i) => { ctx.fillStyle = i === ls.length - 1 ? L.theme.accent : '#ffffff'; ctx.fillText(line, 64, top + i * lh); });
  ctx.restore();
  ctx.fillStyle = L.theme.accent; ctx.fillRect(64, top + ls.length * lh + 18, 140, 10);
  const thumbnail = base + '.thumbnail.jpg';
  fs.writeFileSync(thumbnail, c.toBuffer('image/jpeg', 90));

  // description: hook, chapters, credits
  const first = timeline.find((tl) => tl.scene.say)?.scene.say || '';
  const ch = chapters(timeline);
  const lines = [
    spec.title,
    '',
    spec.description || first,
    '',
    ...(ch.length ? ['Chapters', ...ch.map((c) => `${stamp(c.at)} ${c.label}`), ''] : []),
    ...(credits.length ? ['Image credits (Wikimedia Commons)', ...credits.map((cr) => `- "${cr.title}" by ${cr.author}, ${cr.license}: ${cr.url}`), ''] : []),
    ...(spec.music && !/[\\/.]/.test(spec.music) ? ['Music: original score generated by makevideo (royalty-free).', ''] : []),
    'Made with makevideo: https://github.com/random00000000/makevideo',
  ];
  const description = base + '.description.txt';
  fs.writeFileSync(description, lines.join('\n') + '\n');
  return { thumbnail, description, chapters: ch.map((c) => ({ at: +c.at.toFixed(2), label: c.label })) };
}
